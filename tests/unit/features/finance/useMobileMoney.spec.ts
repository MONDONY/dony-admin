import { describe, it, expect, vi, beforeEach } from 'vitest'
vi.mock('@/features/finance/services/financeService')
import { useMobileMoney } from '@/features/finance/composables/useMobileMoney'
import { financeService } from '@/features/finance/services/financeService'
const svc = financeService as any

const page = (content: object[] = [], over: object = {}) => ({ content, totalElements: content.length, totalPages: 3, number: 0, size: 20, ...over })
const COUNTS = { failed: 2, open: 1, done: 7, all: 10, attention: 2 }
const missing = () => Object.assign(new Error('nf'), { statusCode: 404, data: {} })
const row = (id: string, provider = 'ORANGE_CIV') => ({ id, provider, kind: 'DEPOSIT' })

beforeEach(() => {
  vi.clearAllMocks()
  svc.listMobileMoneyPayments = vi.fn().mockResolvedValue(page([row('a')]))
  svc.mobileMoneyCounts = vi.fn().mockResolvedValue(COUNTS)
})

describe('useMobileMoney', () => {
  it('load : vue Échecs par défaut quand attention > 0, liste demandée avec view=FAILED', async () => {
    const m = useMobileMoney()
    await m.load({})
    expect(m.filters.view).toBe('FAILED')
    expect(svc.listMobileMoneyPayments).toHaveBeenCalledTimes(1)
    expect(svc.listMobileMoneyPayments.mock.calls[0][0]).toMatchObject({ view: 'FAILED', page: 0 })
    expect(m.rows.value).toHaveLength(1)
    expect(m.counts.value).toEqual(COUNTS)
    expect(m.viewsReady.value).toBe(true)
  })
  it('load : vue Toutes par défaut quand rien à traiter', async () => {
    svc.mobileMoneyCounts.mockResolvedValue({ ...COUNTS, attention: 0 })
    const m = useMobileMoney()
    await m.load({})
    expect(m.filters.view).toBe('ALL')
  })
  it('load : la vue de l’URL gagne sur le défaut, kind/provider/query aussi', async () => {
    const m = useMobileMoney()
    await m.load({ view: 'done', kind: 'PAYOUT', provider: 'WAVE_SEN', query: 'awa' })
    expect(m.filters).toMatchObject({ view: 'DONE', kind: 'PAYOUT', provider: 'WAVE_SEN', query: 'awa' })
    expect(svc.mobileMoneyCounts).toHaveBeenCalledWith(expect.objectContaining({ kind: 'PAYOUT', provider: 'WAVE_SEN', q: 'awa' }))
  })
  it('les nombres ignorent la vue', async () => {
    const m = useMobileMoney()
    await m.load({})
    expect(svc.mobileMoneyCounts.mock.calls[0][0].view).toBeUndefined()
  })
  it('ancien back : nombres absents => indisponible, vue Toutes, liste plate sans nombres', async () => {
    svc.mobileMoneyCounts.mockRejectedValue(missing())
    const m = useMobileMoney()
    await m.load({ view: 'failed' })
    expect(m.unavailable.value).toBe(true)
    expect(m.counts.value).toBeNull()
    expect(m.viewsReady.value).toBe(false)
    expect(m.filters.view).toBe('ALL')
    expect(svc.listMobileMoneyPayments.mock.calls[0][0].view).toBe('ALL')
    expect(m.rows.value).toHaveLength(1)
  })
  it('réponse de nombres sans forme attendue (ex. page de liste) => indisponible', async () => {
    svc.mobileMoneyCounts.mockResolvedValue(page([row('a')]))
    const m = useMobileMoney()
    await m.load({})
    expect(m.unavailable.value).toBe(true)
    expect(m.counts.value).toBeNull()
  })
  it('erreur de nombres autre que 404 : message, vues cachées, liste quand même chargée', async () => {
    svc.mobileMoneyCounts.mockRejectedValue(Object.assign(new Error('x'), { statusCode: 500 }))
    const m = useMobileMoney()
    await m.load({})
    expect(m.countsError.value).toBeTruthy()
    expect(m.unavailable.value).toBe(false)
    expect(m.filters.view).toBe('ALL')
    expect(m.rows.value).toHaveLength(1)
  })
  it('setView remet la page à 0 et recharge la liste (pas les nombres)', async () => {
    const m = useMobileMoney()
    await m.load({})
    await m.goToPage(2)
    expect(svc.listMobileMoneyPayments.mock.calls.at(-1)[0]).toMatchObject({ page: 2 })
    svc.mobileMoneyCounts.mockClear()
    await m.setView('OPEN')
    expect(svc.listMobileMoneyPayments.mock.calls.at(-1)[0]).toMatchObject({ view: 'OPEN', page: 0 })
    expect(m.currentPage.value).toBe(0)
    expect(svc.mobileMoneyCounts).not.toHaveBeenCalled()
  })
  it('setKind / setProvider / setQuery : page 0, liste ET nombres relus avec le périmètre', async () => {
    const m = useMobileMoney()
    await m.load({})
    await m.goToPage(1)
    await m.setKind('REFUND')
    expect(svc.listMobileMoneyPayments.mock.calls.at(-1)[0]).toMatchObject({ kind: 'REFUND', page: 0 })
    expect(svc.mobileMoneyCounts.mock.calls.at(-1)[0]).toMatchObject({ kind: 'REFUND' })
    await m.setProvider('WAVE_SEN')
    await m.setQuery('YD-123')
    expect(svc.listMobileMoneyPayments.mock.calls.at(-1)[0]).toMatchObject({ kind: 'REFUND', provider: 'WAVE_SEN', q: 'YD-123' })
    expect(svc.mobileMoneyCounts.mock.calls.at(-1)[0]).toMatchObject({ provider: 'WAVE_SEN', q: 'YD-123' })
  })
  it('le choix de l’utilisateur n’est pas écrasé par le défaut quand les nombres arrivent après', async () => {
    let resolveCounts!: (_v: unknown) => void
    svc.mobileMoneyCounts.mockReturnValue(new Promise(r => { resolveCounts = r }))
    const m = useMobileMoney()
    const loading = m.load({})
    await m.setView('DONE')
    resolveCounts(COUNTS)
    await loading
    expect(m.filters.view).toBe('DONE')
    expect(svc.listMobileMoneyPayments.mock.calls.at(-1)[0].view).toBe('DONE')
  })
  it('réponse de liste périmée ignorée', async () => {
    const m = useMobileMoney()
    await m.load({})
    let first!: (_v: unknown) => void
    svc.listMobileMoneyPayments.mockReturnValueOnce(new Promise(r => { first = r }))
    svc.listMobileMoneyPayments.mockResolvedValueOnce(page([row('new')]))
    const a = m.setView('OPEN'); const b = m.setView('DONE')
    await b; first(page([row('old')])); await a
    expect(m.rows.value.map((r: any) => r.id)).toEqual(['new'])
  })
  it('erreur de liste : message, aucune ligne d’une autre vue', async () => {
    const m = useMobileMoney()
    await m.load({})
    svc.listMobileMoneyPayments.mockRejectedValueOnce(Object.assign(new Error('x'), { statusCode: 500 }))
    await m.setView('OPEN')
    expect(m.error.value).toBeTruthy()
    expect(m.rows.value).toEqual([])
  })
  it('providers : opérateurs vus dans les listes chargées, cumulés', async () => {
    svc.listMobileMoneyPayments.mockResolvedValueOnce(page([row('a', 'ORANGE_CIV'), row('b', 'WAVE_SEN')]))
    const m = useMobileMoney()
    await m.load({})
    svc.listMobileMoneyPayments.mockResolvedValueOnce(page([row('c', 'MTN_MOMO_CIV')]))
    await m.setProvider('MTN_MOMO_CIV')
    expect(m.providers.value).toEqual(['MTN_MOMO_CIV', 'ORANGE_CIV', 'WAVE_SEN'])
  })
  it('syncFromQuery : applique une query différente, ne fait rien si elle est déjà reflétée', async () => {
    const m = useMobileMoney()
    await m.load({})
    svc.listMobileMoneyPayments.mockClear()
    await m.syncFromQuery({ view: 'failed' })
    expect(svc.listMobileMoneyPayments).not.toHaveBeenCalled()
    await m.syncFromQuery({ view: 'done', kind: 'PAYOUT' })
    expect(m.filters).toMatchObject({ view: 'DONE', kind: 'PAYOUT' })
    expect(svc.listMobileMoneyPayments).toHaveBeenCalledTimes(1)
  })
  it('applyUrl : écrit les filtres, vue comprise tant que les nombres existent', async () => {
    const m = useMobileMoney()
    await m.load({})
    expect(m.applyUrl({ tab: 'mobile-money' })).toEqual({ tab: 'mobile-money', view: 'failed' })
    svc.mobileMoneyCounts.mockRejectedValue(missing())
    await m.reload()
    expect(m.applyUrl({ tab: 'mobile-money', view: 'failed' })).toEqual({ tab: 'mobile-money' })
  })
  it('reload relit la liste et les nombres', async () => {
    const m = useMobileMoney()
    await m.load({})
    svc.listMobileMoneyPayments.mockClear(); svc.mobileMoneyCounts.mockClear()
    await m.reload()
    expect(svc.listMobileMoneyPayments).toHaveBeenCalledTimes(1)
    expect(svc.mobileMoneyCounts).toHaveBeenCalledTimes(1)
  })
})
